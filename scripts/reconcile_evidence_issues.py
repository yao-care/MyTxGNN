#!/usr/bin/env python3
"""
對帳關閉過期的證據監測 issue（2026-11-03）。

預測清單改過幾輪後，已經開出去的 ClinicalTrials.gov／PubMed 監測 issue 沒有機制回頭關，
這支在 extract_drug_list.py 之後、檢查腳本之前執行，拿目前的 scripts/drug_list.json 對帳。

取全部 open 的 auto-detected 監測 issue（label clinicaltrials 或 pubmed，分頁取完），符合任一條就留言並以
not_planned 關閉：
  (a) 標題沒有「→」（2026-10-16 前只按藥名開的舊版）
  (b) 藥已不在目前的 drug_list
  (c) 內文「### Predicted New Indication(s)」列的預測，一個都不在該藥目前的 predicted_indications
只有部分預測還在的：不關、不留言（避免每次排程重複留言）。

跳過：有 assignee、帶 evidence-confirmed／keep 類／tfda／security 標籤、有非 bot 的人類留言。

每次最多關 RECONCILE_MAX_CLOSE 筆（預設 50），每筆之間 sleep RECONCILE_SLEEP 秒（預設 3，最少 2）。
--dry-run 只列出會關哪些、理由，不寫任何東西；沒有 GITHUB_TOKEN 時自動 dry-run（用無 token 的公開 API 唯讀）。
"""

import argparse
import json
import os
import re
import sys
import time
from pathlib import Path

import requests

from github_utils import GITHUB_REPO, GITHUB_TOKEN, close_issue, get_headers, list_issues, title_drug_name

DRUG_LIST_FILE = Path(__file__).parent / "drug_list.json"
MONITOR_LABELS = ("clinicaltrials", "pubmed")
SKIP_LABELS = {"evidence-confirmed", "tfda", "security"}

COMMENT_HEAD = ("🤖 Auto-closed: the prediction list has been updated, "
                "and the predicted indication(s) listed in this issue are no longer on the drug page.")
COMMENT_REASON = {
    "a": "This issue was opened in the old drug-name-only format (before 2026-10-16) and is not tied to any current predicted indication.",
    "b": "This drug is no longer in the monitored drug list.",
    "c": "None of the predicted indications listed in this issue are in the drug's current prediction list.",
}
COMMENT_TAIL = "If the evidence is still relevant to a current prediction, please reopen this issue."
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def norm(text: str) -> str:
    return " ".join((text or "").lower().split())


def section_lines(body: str, heading: str) -> list:
    """內文「### heading」到下一個「###」之間的「- 項目」。"""
    m = re.search(r"^###\s*" + re.escape(heading) + r"\s*$(.*?)(?=^###\s|\Z)", body or "", re.M | re.S)
    if not m:
        return []
    items = [re.sub(r"^\s*[-*]\s+", "", l).strip() for l in m.group(1).splitlines() if re.match(r"^\s*[-*]\s+\S", l)]
    return [x for x in items if x and x != "-"]


def section_text(body: str, heading: str) -> str:
    m = re.search(r"^###\s*" + re.escape(heading) + r"\s*$\s*^(.+?)$", body or "", re.M)
    return m.group(1).strip() if m else ""


def title_predictions(title: str) -> list:
    if "→" not in title:
        return []
    tail = title.split("→", 1)[1].replace("…", "")
    return [x.strip() for x in tail.split(";") if x.strip()]


def is_bot(user: dict) -> bool:
    user = user or {}
    return user.get("type") == "Bot" or (user.get("login") or "").endswith("[bot]")


def has_human_comment(issue: dict) -> bool:
    """有非 bot 的留言就跳過；查不到時當作有（寧可不關）。"""
    if not issue.get("comments"):
        return False
    url = f"https://api.github.com/repos/{GITHUB_REPO}/issues/{issue['number']}/comments"
    params = {"per_page": 100, "page": 1}
    try:
        while True:
            r = requests.get(url, headers=get_headers(), params=params, timeout=30)
            r.raise_for_status()
            batch = r.json()
            if any(not is_bot(c.get("user")) for c in batch):
                return True
            if len(batch) < 100:
                return False
            params["page"] += 1
    except requests.RequestException as e:
        print(f"  Warning: could not read comments of #{issue['number']} ({e}); skipping it")
        return True


def skip_reason(issue: dict) -> str:
    if issue.get("assignees") or issue.get("assignee"):
        return "assigned"
    for label in (l.get("name", "") for l in issue.get("labels", [])):
        low = label.lower()
        if low in SKIP_LABELS or "keep" in low or "security" in low:
            return f"label:{label}"
    return ""


def stale_reason(issue: dict, drugs: dict) -> str:
    title, body = issue.get("title", ""), issue.get("body") or ""
    if "→" not in title:
        return "a"
    drug_name = section_text(body, "Drug Name") or title_drug_name(title) or ""
    drug = drugs.get(norm(drug_name))
    if drug is None:
        return "b"
    listed = section_lines(body, "Predicted New Indication(s)") or title_predictions(title)
    current = {norm(x) for x in drug.get("predicted_indications") or []}
    if listed and not any(norm(x) in current for x in listed):
        return "c"
    return ""


def load_drugs() -> dict:
    with open(DRUG_LIST_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)
    drugs = {}
    for d in data["drugs"]:
        for key in (d.get("name"), d.get("inn")):
            if key:
                drugs.setdefault(norm(key), d)
    return drugs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true", help="list what would be closed; write nothing")
    ap.add_argument("--max", type=int, default=int(os.environ.get("RECONCILE_MAX_CLOSE", "50")))
    ap.add_argument("--sleep", type=float, default=float(os.environ.get("RECONCILE_SLEEP", "3")))
    args = ap.parse_args()
    dry = args.dry_run or not GITHUB_TOKEN
    pause = max(2.0, args.sleep)

    print("=" * 60)
    print(f"Reconcile evidence-monitor issues ({GITHUB_REPO}){' [DRY RUN]' if dry else ''}")
    print("=" * 60)

    drugs = load_drugs()
    issues = {}
    for label in MONITOR_LABELS:
        for issue in list_issues(f"auto-detected,{label}", state="open"):
            issues[issue["number"]] = issue
    print(f"Open monitor issues: {len(issues)}; monitored drugs: {len({id(d) for d in drugs.values()})}")

    candidates, skipped, partial = [], {}, 0
    for number in sorted(issues):
        issue = issues[number]
        reason = stale_reason(issue, drugs)
        if not reason:
            partial += 1
            continue
        why = skip_reason(issue) or ("human-comment" if has_human_comment(issue) else "")
        if why:
            skipped[why] = skipped.get(why, 0) + 1
            print(f"  skip #{number} ({why}) [{reason}] {issue['title']}")
            continue
        candidates.append((number, reason, issue["title"]))

    by_reason = {r: sum(1 for c in candidates if c[1] == r) for r in "abc"}
    print(f"\nStill current (some listed prediction still on the page): {partial}")
    print(f"Skipped: {skipped or 0}")
    print(f"Stale: {len(candidates)}  (a) old format {by_reason['a']}, (b) drug gone {by_reason['b']}, "
          f"(c) predictions gone {by_reason['c']}")
    print(f"Will close this run: {min(len(candidates), args.max)} (max {args.max})")

    for i, (number, reason, title) in enumerate(candidates):
        if i >= args.max:
            print(f"  … {len(candidates) - args.max} more left for the next run")
            break
        if dry:
            print(f"  [DRY RUN] would close #{number} ({reason}) {title}")
            continue
        comment = f"{COMMENT_HEAD}\n\n{COMMENT_REASON[reason]} {COMMENT_TAIL}{FOOTER}"
        print(f"  closing #{number} ({reason}) {title}")
        close_issue(number, comment, state_reason="not_planned")
        time.sleep(pause)
    return 0


if __name__ == "__main__":
    sys.exit(main())
